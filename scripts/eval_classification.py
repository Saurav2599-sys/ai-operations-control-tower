"""Phase 3 eval: how well does classify_order() actually extract skills and
priority from free-text descriptions? Run it yourself -- this script is
the source of the numbers in the README's "Phase 3 eval results" section,
not the other way around, same as scripts/benchmark.py is for Phase 2.

    python -m scripts.eval_classification

Needs a real OPENAI_API_KEY in your environment/.env -- this makes actual
API calls (18 of them), unlike scripts/benchmark.py which is pure
in-memory computation. Costs a small, real amount of money each run.

The eval set below is hand-labeled by me, not scraped or generated by an
LLM -- 18 realistic work-order descriptions, spanning all 8 skills in
app/constants.SKILL_POOL and all 4 priority levels, with the required
skill set and expected priority I'd assign reading them myself. That's a
small, subjective ground truth, not a rigorous benchmark -- it's enough to
catch obviously bad extractions and to have a real, reproducible number
instead of a vibe. See the README for that caveat spelled out.
"""

