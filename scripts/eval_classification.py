def _prf1(predicted: frozenset[str], expected: frozenset[str]) -> tuple[float, float, float]:
    if not predicted and not expected:
        return 1.0, 1.0, 1.0
    if not predicted or not expected:
        return 0.0, 0.0, 0.0
    tp = len(predicted & expected)
    precision = tp / len(predicted)
    recall = tp / len(expected)
    f1 = 2 * precision * recall / (precision + recall) if (precision + recall) else 0.0
    return precision, recall, f1


def main() -> None:
    if not os.getenv("OPENAI_API_KEY"):
        raise SystemExit(
            "OPENAI_API_KEY not set -- add it to .env or export it before running this."
        )

    rows = []
    failures = 0
    total_elapsed = 0.0

    for i, case in enumerate(EVAL_CASES, start=1):
        start = time.perf_counter()
        try:
            result = classify_order(case.description)
        except ClassificationError as exc:
            failures += 1
            print(f"[{i:2d}] FAILED: {exc}  -- {case.description[:60]!r}")
            continue
        elapsed = time.perf_counter() - start
        total_elapsed += elapsed

        precision, recall, f1 = _prf1(result.suggested_skills, case.expected_skills)
        priority_correct = result.suggested_priority == case.expected_priority
        exact_skill_match = result.suggested_skills == case.expected_skills

        rows.append(
            {
                "precision": precision,
                "recall": recall,
                "f1": f1,
                "exact_skill_match": exact_skill_match,
                "priority_correct": priority_correct,
                "confidence": result.confidence,
            }
        )

        mark = "✓" if exact_skill_match else "✗"
        pmark = "✓" if priority_correct else "✗"
        print(
            f"[{i:2d}] skills {mark} (P={precision:.2f} R={recall:.2f} F1={f1:.2f})  "
            f"priority {pmark} (got={result.suggested_priority}, want={case.expected_priority})  "
            f"conf={result.confidence:.2f}"
        )
        print(f"     predicted: {sorted(result.suggested_skills) or '[]'}")
        print(f"     expected:  {sorted(case.expected_skills)}")

    n = len(rows)
    if n == 0:
        print("\nNo successful classifications -- nothing to summarize.")
        return

    mean_precision = sum(r["precision"] for r in rows) / n
    mean_recall = sum(r["recall"] for r in rows) / n
    mean_f1 = sum(r["f1"] for r in rows) / n
    exact_match_rate = sum(r["exact_skill_match"] for r in rows) / n
    priority_accuracy = sum(r["priority_correct"] for r in rows) / n
    mean_confidence = sum(r["confidence"] for r in rows) / n
    mean_latency = total_elapsed / n

    print(f"\n{'':<28}{'Value':<10}")
    print("-" * 38)
    print(f"{'Cases evaluated':<28}{n}/{len(EVAL_CASES)}")
    print(f"{'Failed calls':<28}{failures}")
    print(f"{'Skill exact-match rate':<28}{exact_match_rate * 100:.1f}%")
    print(f"{'Skill precision (mean)':<28}{mean_precision * 100:.1f}%")
    print(f"{'Skill recall (mean)':<28}{mean_recall * 100:.1f}%")
    print(f"{'Skill F1 (mean)':<28}{mean_f1 * 100:.1f}%")
    print(f"{'Priority accuracy':<28}{priority_accuracy * 100:.1f}%")
    print(f"{'Mean confidence reported':<28}{mean_confidence:.2f}")
    print(f"{'Mean latency/call':<28}{mean_latency:.2f}s")


if __name__ == "__main__":
    main()
